def test_the_trainer_image_pins_the_converter_by_tag_and_checksum():
    text = (Path(__file__).resolve().parents[1] / "docker" / "Dockerfile.trainer").read_text()
    assert "ARG LLAMACPP_TAG=b6000" in text
    sha = next(l for l in text.splitlines() if l.startswith("ARG CONVERTER_SHA256=")).split("=")[1]
    assert len(sha) == 64 and set(sha) <= set("0123456789abcdef")
    assert "sha256sum -c" in text and "gguf" in text and "sentencepiece" in text
    assert f"ENV {trainer.GGUF_CONVERTER_ENV}=/opt/llama.cpp/convert_hf_to_gguf.py" in text
