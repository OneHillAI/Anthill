"""A trained adapter is merged into its base and registered as a GGUF, which every Ollama accepts (#273).

Ollama 0.34.1 and later refuse `ollama create ... ADAPTER`. The training image merges the adapter into the base and
converts it with llama.cpp's converter (`trainer.merge_adapter_to_gguf`, run by `train_adapter` when the converter is
configured); the org machine registers `merged.gguf` with the base model's own template (`register_with_ollama`).
No GPU, model or Ollama is used here: the heavy libraries, the converter and `ollama create` are faked.
"""

import subprocess
import sys
import types
from pathlib import Path

import httpx
import pytest

from anthill.training import trainer
from anthill.training.trainer import TrainerError

BASE_MODELFILE = (
    '# Modelfile generated by "ollama show"\n'
    "FROM /root/.ollama/models/blobs/sha256-abc\n"
    'TEMPLATE """{{ .Prompt }}"""\n'
    "PARAMETER stop <|im_end|>\n"
    "ADAPTER /old/adapter\n"
)


@pytest.fixture
def fake_libs(monkeypatch):
    """torch, peft and transformers stand-ins that record what the merge does."""
    calls = []

    class _Merged:
        def save_pretrained(self, path, safe_serialization=True):
            calls.append(("save_merged", path))

    class _Peft:
        @staticmethod
        def from_pretrained(base, adapter_dir):
            calls.append(("peft", adapter_dir))
            return types.SimpleNamespace(merge_and_unload=lambda: _Merged())

    class _Auto:
        @staticmethod
        def from_pretrained(name, **kw):
            calls.append(("base", name))
            return object()

    class _Tok:
        @staticmethod
        def from_pretrained(name):
            return types.SimpleNamespace(save_pretrained=lambda p: calls.append(("save_tok", p)))

    monkeypatch.setitem(sys.modules, "torch", types.SimpleNamespace(bfloat16="bf16"))
    monkeypatch.setitem(sys.modules, "peft", types.SimpleNamespace(PeftModel=_Peft))
    monkeypatch.setitem(
        sys.modules,
        "transformers",
        types.SimpleNamespace(AutoModelForCausalLM=_Auto, AutoTokenizer=_Tok),
    )
    return calls


def _converter(tmp_path):
    script = tmp_path / "convert_hf_to_gguf.py"
    script.write_text("# stand-in")
    return str(script)


def _fake_convert(monkeypatch, *, ok=True, seen=None):
    def run(cmd, **kw):
        if seen is not None:
            seen.append(cmd)
        if ok:
            Path(cmd[cmd.index("--outfile") + 1]).write_bytes(b"GGUF")
        return subprocess.CompletedProcess(
            cmd, 0 if ok else 1, "", "" if ok else "boom: bad tensor"
        )

    monkeypatch.setattr(trainer.subprocess, "run", run)


# ── merge and convert (the training image) ───────────────────────────────────────────────────────────────────


def test_the_adapter_is_merged_and_converted_next_to_the_adapter(tmp_path, monkeypatch, fake_libs):
    adapter = tmp_path / "adapter"
    adapter.mkdir()
    seen = []
    _fake_convert(monkeypatch, seen=seen)
    out = trainer.merge_adapter_to_gguf(
        str(adapter), "qwen2.5:0.5b", converter=_converter(tmp_path)
    )
    assert out == str(adapter / trainer.MERGED_GGUF_NAME) and Path(out).is_file()
    assert ("base", "Qwen/Qwen2.5-0.5B-Instruct") in fake_libs  # the same HF base the training used
    assert ("peft", str(adapter)) in fake_libs
    cmd = seen[0]
    assert cmd[0] == sys.executable and cmd[1].endswith("convert_hf_to_gguf.py")
    assert cmd[cmd.index("--outtype") + 1] == "q8_0" and cmd[cmd.index("--outfile") + 1] == out


def test_the_temporary_merged_folder_is_removed(tmp_path, monkeypatch, fake_libs):
    adapter = tmp_path / "adapter"
    adapter.mkdir()
    _fake_convert(monkeypatch)
    trainer.merge_adapter_to_gguf(str(adapter), "qwen2.5:0.5b", converter=_converter(tmp_path))
    work = Path(next(p for k, p in fake_libs if k == "save_merged"))
    assert not work.exists()


def test_a_missing_converter_or_a_failing_one_is_a_plain_error(tmp_path, monkeypatch, fake_libs):
    adapter = tmp_path / "adapter"
    adapter.mkdir()
    with pytest.raises(TrainerError, match="converter was not found"):
        trainer.merge_adapter_to_gguf(
            str(adapter), "qwen2.5:0.5b", converter=str(tmp_path / "nope.py")
        )
    _fake_convert(monkeypatch, ok=False)
    with pytest.raises(
        TrainerError, match=r"Converting the merged model to GGUF failed: .*bad tensor"
    ):
        trainer.merge_adapter_to_gguf(str(adapter), "qwen2.5:0.5b", converter=_converter(tmp_path))


def test_missing_libraries_are_a_plain_error(tmp_path, monkeypatch):
    monkeypatch.setitem(sys.modules, "peft", None)  # makes `import peft` fail
    with pytest.raises(TrainerError, match="merge toolchain is not importable"):
        trainer.merge_adapter_to_gguf("x", "qwen2.5:0.5b", converter=_converter(tmp_path))


def test_a_peft_run_writes_the_merged_file_only_when_the_image_configures_the_converter(
    tmp_path, monkeypatch
):
    merged = []
    monkeypatch.setattr(trainer, "_train_peft", lambda *a, **k: str(tmp_path / "adapter"))
    monkeypatch.setattr(
        trainer, "merge_adapter_to_gguf", lambda d, b, **k: merged.append((d, b, k)) or "x"
    )
    monkeypatch.delenv(trainer.GGUF_CONVERTER_ENV, raising=False)
    trainer.train_adapter("d.jsonl", "qwen2.5:0.5b", out_dir=str(tmp_path / "o"), toolchain="peft")
    assert merged == []
    monkeypatch.setenv(trainer.GGUF_CONVERTER_ENV, "/opt/llama.cpp/convert_hf_to_gguf.py")
    monkeypatch.setenv(trainer.GGUF_OUTTYPE_ENV, "f16")
    trainer.train_adapter("d.jsonl", "qwen2.5:0.5b", out_dir=str(tmp_path / "o"), toolchain="peft")
    assert merged == [
        (
            str(tmp_path / "adapter"),
            "qwen2.5:0.5b",
            {"converter": "/opt/llama.cpp/convert_hf_to_gguf.py", "outtype": "f16"},
        )
    ]


def test_a_failed_merge_never_loses_the_adapter(tmp_path, monkeypatch, capsys):
    monkeypatch.setattr(trainer, "_train_peft", lambda *a, **k: str(tmp_path / "adapter"))

    def boom(*a, **k):
        raise TrainerError("no memory")

    monkeypatch.setattr(trainer, "merge_adapter_to_gguf", boom)
    monkeypatch.setenv(trainer.GGUF_CONVERTER_ENV, "/opt/c.py")
    out = trainer.train_adapter(
        "d.jsonl", "qwen2.5:0.5b", out_dir=str(tmp_path / "o"), toolchain="peft"
    )
    assert out == str(tmp_path / "adapter")
    assert "no merged GGUF was produced" in capsys.readouterr().err


def test_the_mlx_path_does_not_merge(tmp_path, monkeypatch):
    monkeypatch.setattr(trainer, "_train_mlx", lambda *a, **k: str(tmp_path / "mlx"))
    monkeypatch.setattr(
        trainer, "_merge_to_gguf_if_configured", lambda *a: pytest.fail("MLX must not merge")
    )
    trainer.train_adapter("d.jsonl", "qwen2.5:0.5b", out_dir=str(tmp_path / "o"), toolchain="mlx")


# ── registering the merged file (the org machine) ────────────────────────────────────────────────────────────


def _show(monkeypatch, text=BASE_MODELFILE, *, fail=False):
    def post(url, json=None, timeout=None):
        if fail:
            raise httpx.ConnectError("down")
        return types.SimpleNamespace(json=lambda: {"modelfile": text})

    monkeypatch.setattr(trainer.httpx, "post", post)


def _adapter_dir(tmp_path, *, merged=True):
    d = tmp_path / "adapter"
    d.mkdir()
    (d / "adapter_model.safetensors").write_bytes(b"x")
    if merged:
        (d / trainer.MERGED_GGUF_NAME).write_bytes(b"GGUF")
    return d


def test_the_merged_file_is_registered_with_the_base_template_and_no_adapter(tmp_path, monkeypatch):
    d = _adapter_dir(tmp_path)
    _show(monkeypatch)
    monkeypatch.setattr(trainer, "find_ollama_bin", lambda: "/engine/ollama")
    seen = []
    monkeypatch.setattr(
        trainer.subprocess,
        "run",
        lambda cmd, **kw: seen.append(cmd) or subprocess.CompletedProcess(cmd, 0, "", ""),
    )
    trainer.register_with_ollama("org1-model-v1", "qwen2.5:0.5b", str(d))
    assert seen[0][:3] == ["/engine/ollama", "create", "org1-model-v1"]
    text = Path(seen[0][seen[0].index("-f") + 1]).read_text()
    assert text.splitlines()[0] == f"FROM {(d / 'merged.gguf').resolve()}"
    assert (
        "/root/.ollama/models/blobs" not in text and "ADAPTER" not in text
    )  # the base weights and adapter lines go
    assert (
        'TEMPLATE """{{ .Prompt }}"""' in text and "PARAMETER stop <|im_end|>" in text
    )  # the template stays


def test_a_relative_path_is_made_absolute_so_ollama_does_not_read_it_as_a_registry_name(
    tmp_path, monkeypatch
):
    _adapter_dir(tmp_path)
    _show(monkeypatch)
    monkeypatch.setattr(trainer, "find_ollama_bin", lambda: "ollama")
    seen = []
    monkeypatch.setattr(
        trainer.subprocess,
        "run",
        lambda cmd, **kw: seen.append(cmd) or subprocess.CompletedProcess(cmd, 0, "", ""),
    )
    monkeypatch.chdir(tmp_path)
    trainer.register_with_ollama("m", "qwen2.5:0.5b", "adapter")
    assert Path(
        Path(seen[0][seen[0].index("-f") + 1]).read_text().splitlines()[0][5:]
    ).is_absolute()


def test_without_a_merged_file_the_adapter_route_is_unchanged(tmp_path, monkeypatch):
    d = _adapter_dir(tmp_path, merged=False)
    monkeypatch.setattr(trainer, "find_ollama_bin", lambda: "ollama")
    seen = []
    monkeypatch.setattr(
        trainer.subprocess,
        "run",
        lambda cmd, **kw: seen.append(cmd) or subprocess.CompletedProcess(cmd, 0, "", ""),
    )
    trainer.register_with_ollama("m", "qwen3:8b", str(d))
    assert f"ADAPTER {d}" in (tmp_path / "Modelfile.m").read_text()
    monkeypatch.setattr(
        trainer.subprocess,
        "run",
        lambda cmd, **kw: subprocess.CompletedProcess(
            cmd, 1, "", "Error: LoRA adapters are no longer supported"
        ),
    )
    with pytest.raises(TrainerError) as err:
        trainer.register_with_ollama("m", "qwen3:8b", str(d))
    assert str(err.value) == trainer.ADAPTERS_REFUSED_NOTE and "image" in str(err.value)


def test_an_unreadable_base_or_a_failed_creation_is_a_plain_error(tmp_path, monkeypatch):
    d = _adapter_dir(tmp_path)
    _show(monkeypatch, fail=True)
    with pytest.raises(TrainerError, match=r"Could not read the base model qwen2\.5:0\.5b"):
        trainer.register_with_ollama("m", "qwen2.5:0.5b", str(d))
    _show(monkeypatch, text="")
    with pytest.raises(TrainerError, match="no Modelfile for the base model"):
        trainer.register_with_ollama("m", "qwen2.5:0.5b", str(d))
    _show(monkeypatch)
    monkeypatch.setattr(trainer, "find_ollama_bin", lambda: "ollama")
    monkeypatch.setattr(
        trainer.subprocess,
        "run",
        lambda cmd, **kw: subprocess.CompletedProcess(cmd, 1, "", "Error: bad gguf"),
    )
    with pytest.raises(TrainerError, match=r"`ollama create m` failed: .*bad gguf"):
        trainer.register_with_ollama("m", "qwen2.5:0.5b", str(d))


def test_the_eval_gate_still_rejects_and_removes_a_losing_merged_model(tmp_path, monkeypatch):
    d = _adapter_dir(tmp_path)
    registered, removed = [], []
    monkeypatch.setattr(
        trainer, "_register_merged_gguf", lambda name, base, gguf: registered.append((name, gguf))
    )
    monkeypatch.setattr(trainer, "remove_from_ollama", lambda name: removed.append(name))
    monkeypatch.setattr(
        trainer,
        "evaluate_models",
        lambda *a, **k: types.SimpleNamespace(winner="live", summary=lambda: "lost"),
    )
    out = trainer.promote_if_better(
        str(d),
        base_model="qwen2.5:0.5b",
        model_name="cand",
        version=2,
        eval_examples=[("q", "a")],
        current_model="live",
        inference_backend=object(),
    )
    assert registered == [("cand", str(d / "merged.gguf"))] and removed == ["cand"]
    assert (
        out.won_eval is False and out.model_version is None
    )  # a rejected candidate never replaces the live model


